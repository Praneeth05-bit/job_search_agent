"""Boundary tests for the search contract (SearchQuery).

These rules are the first defense against bad input, including tool calls
generated by the LLM. Each rule is tested just inside and just outside its
limit.
"""

import pytest
from pydantic import ValidationError

from job_search_agent.domain.models import OpportunityType
from job_search_agent.retrieval.schemas import SearchQuery


@pytest.mark.parametrize("limit", [1, 30])
def test_limit_inside_bounds_is_accepted(limit: int) -> None:
    """The lowest and highest allowed limits are valid."""
    assert SearchQuery(text="python", limit=limit).limit == limit


@pytest.mark.parametrize("limit", [0, 31])
def test_limit_outside_bounds_is_rejected(limit: int) -> None:
    """One below the minimum and one above the maximum are refused."""
    with pytest.raises(ValidationError):
        SearchQuery(text="python", limit=limit)


def test_defaults_are_applied() -> None:
    """Only text is required; type defaults to any and limit to 10."""
    query = SearchQuery(text="python")

    assert query.opportunity_type is None
    assert query.limit == 10


def test_empty_text_is_rejected() -> None:
    """A search needs at least one character."""
    with pytest.raises(ValidationError):
        SearchQuery(text="")


def test_known_type_string_is_converted_to_enum() -> None:
    """JSON sends plain strings; the model turns them into the enum."""
    query = SearchQuery(text="python", opportunity_type="internship")

    assert query.opportunity_type is OpportunityType.INTERNSHIP


def test_unknown_type_is_rejected() -> None:
    """Only internship, job, or research are allowed."""
    with pytest.raises(ValidationError):
        SearchQuery(text="python", opportunity_type="contract")


def test_extra_field_is_rejected() -> None:
    """Invented parameters (for example from an LLM) are refused."""
    with pytest.raises(ValidationError):
        SearchQuery(text="python", salary_min=50000)  # type: ignore[call-arg]


def test_query_is_frozen() -> None:
    """A query cannot be changed after it is created."""
    query = SearchQuery(text="python")

    with pytest.raises(ValidationError):
        query.limit = 5  # type: ignore[misc]
